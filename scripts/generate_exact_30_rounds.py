def main():
    lines = []
    
    # 1. Rounds 1 to 15
    for r_idx, matches in enumerate(rounds_1_to_15, 1):
        lines.append(f"{r_idx} Тур")
        for h, a in matches:
            lines.append(f"{h} - {a}")
        lines.append("")
        
    # 2. Rounds 16 to 30 (Reverse fixtures of 1 to 15)
    for r_idx, matches in enumerate(rounds_1_to_15, 16):
        lines.append(f"{r_idx} Тур")
        # Relative index in rounds_1_to_15
        orig_matches = rounds_1_to_15[r_idx - 16]
        for h, a in orig_matches:
            lines.append(f"{a} - {h}") # Swapped home and away!
        lines.append("")
        
    text = "\n".join(lines)
    file_path = r"C:\Users\Ислам\Desktop\Projects\logovobot\schedule_30_rounds.txt"
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(text)
        
    print(f"Written 30 rounds (240 matches) to {file_path}")
    
    # Parse and save directly into league.db
    rounds_data, errors = parse_schedule_text(text)
    r_cnt, m_cnt, unmatched = create_matches_from_parsed_schedule(rounds_data)
    
    print(f"\nDB Sync Results:")
    print(f" - Rounds Created: {r_cnt}")
    print(f" - Matches Created: {m_cnt}")
    print(f" - Unmatched Teams: {unmatched}")

if __name__ == "__main__":
    main()
