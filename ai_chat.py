def generate_chat_reply(
    user_id: int, 
    user_text: str, 
    chat_history: list[dict], 
    context_data: str,
    audio_bytes: bytes = None,
    audio_mime: str = "audio/ogg",
    mode: str = "temshik"
) -> str:
    """
    Sends chat history and current user text to an OpenAI-compatible API (ClaudeHub/Qwen) for a conversational response.
    Returns the text reply from the AI.
    """
    api_key = config.OPENAI_CHAT_API_KEY
    if not api_key:
        logger.warning("OPENAI_CHAT_API_KEY is not set.")
        return "Ошибка: Не настроен ключ для чата (OPENAI_CHAT_API_KEY)."
        
    base_url = config.OPENAI_BASE_URL
    model_name = config.OPENAI_CHAT_MODEL

    if mode == "persona2":
        system_instruction = _build_persona2_instruction(context_data)
    else:
        system_instruction = _build_temshik_instruction(context_data)

    messages = [
        {"role": "system", "content": system_instruction}
    ]
    
    for msg in chat_history:
        role = "assistant" if msg["role"] == "model" else msg["role"]
        messages.append({
            "role": role,
            "content": msg["text"]
        })
    
    if audio_bytes:
        messages.append({
            "role": "user", 
            "content": "(Пользователь прислал голосовое сообщение, но текстовая модель не умеет слушать аудио. Ответь, что ты пока не можешь слушать голосовые и попроси написать текстом.)"
        })
    else:
        messages.append({
            "role": "user",
            "content": user_text
        })

    payload = {
        "model": model_name,
        "messages": messages,
        "temperature": 0.8,
        "max_tokens": 500,
    }
    
    payload_bytes = json.dumps(payload).encode('utf-8')

    # Reusing the opener logic for proxy support if needed
    from ai_recognizer import _get_gemini_opener
    opener = _get_gemini_opener()

    url = f"{base_url}/chat/completions"
    req = urllib.request.Request(
        url, 
        data=payload_bytes, 
        headers={
            'Content-Type': 'application/json',
            'Authorization': f'Bearer {api_key}'
        }
    )
    
    try:
        with opener.open(req, timeout=25) as response:
            result = json.loads(response.read().decode('utf-8'))
            
            if "choices" not in result or not result["choices"]:
                logger.warning(f"AI Chat: No choices returned from model '{model_name}'. Response: {result}")
                return "Ошибка генерации ответа."
            
            text_response = result["choices"][0]["message"]["content"]
            clean_text = text_response.replace("**", "").replace("*", "")
            cleaned_lines = [line.strip() for line in clean_text.split("\n")]
            return "\n".join(cleaned_lines).strip()
            
    except urllib.error.HTTPError as e:
        logger.warning(f"AI Chat: Model '{model_name}' HTTP Error {e.code}: {e.read().decode('utf-8')}")
        return "Ох, шлюз API сейчас недоступен (ошибка соединения), попробуй написать попозже! ⚽"
    except Exception as e:
        logger.exception(f"AI Chat: Unexpected error generating reply with model '{model_name}'")
        return "Ох, что-то я сейчас не в форме (ошибка API), попробуй написать попозже! ⚽"

